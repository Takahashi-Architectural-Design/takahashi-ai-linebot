# 公式文書の登録先。原文をここに置くと参照軸として読み込まれる。
DOCS_DIR = os.environ.get("JCI_DOCS_DIR", os.path.join(os.path.dirname(__file__), "data", "jci_docs"))
MAX_DOC_CHARS = 12000


def load_official_docs(docs_dir: str = DOCS_DIR) -> str:
    """data/jci_docs 配下の公式文書（原文）を読み込む。README.md は説明書なので除く。"""
    if not os.path.isdir(docs_dir):
        return ""

    chunks = []
    total = 0
    for path in sorted(glob.glob(os.path.join(docs_dir, "*.md")) + glob.glob(os.path.join(docs_dir, "*.txt"))):
        if os.path.basename(path).lower() == "readme.md":
            continue
        try:
            with open(path, encoding="utf-8") as f:
                text = f.read().strip()
        except OSError:
            continue
        if not text:
            continue
        remain = MAX_DOC_CHARS - total
        if remain <= 0:
            break
        if len(text) > remain:
            text = text[:remain] + "\n（以下省略）"
        chunks.append(f"--- {os.path.basename(path)} ---\n{text}")
        total += len(text)

    if not chunks:
        return ""
    return "【登録済みのJCI公式文書（原文。ここに書かれていることは原文として扱う）】\n" + "\n\n".join(chunks)


def build_system_prompt(base: str, docs_dir: str = DOCS_DIR) -> str:
    """JC室長のシステムプロンプトに、仙台の事業構築とJCI整合の判断軸を足す。"""
    docs = load_official_docs(docs_dir)
    if docs:
        docs_section = docs
    else:
        docs_section = (
            "【JCI公式文書】未登録。\n"
            "Plan of Action・アワード要項・申請様式の原文は登録されていない。\n"
            "年度方針や配点を問われたら、記憶や推測で答えず、原文の確認を促すこと。"
        )

    return "\n\n".join([
        base.strip(),
        STANCE,
        BUILD_ORDER,
        JCI_REFERENCE,
        AWARD_AXES,
        CHECK_QUESTIONS,
        TRANSLATION_GUIDE,
        GUARDRAILS,
        docs_section,
        "【応答のしかた】LINEで読むので簡潔に。相談が曖昧なときは、"
        "上の問いのうち最も欠けている1〜2点だけを聞き返す。全部並べない。",
    ])


